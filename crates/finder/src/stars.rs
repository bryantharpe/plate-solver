/// The proper name of a Hipparcos star, when it has one here.
pub fn name_of(hip: u32) -> Option<&'static str> {
    NAMED_STARS
        .binary_search_by_key(&hip, |s| s.0)
        .ok()
        .map(|i| NAMED_STARS[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_unique_and_found() {
        assert!(NAMED_STARS.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(name_of(27989), Some("Betelgeuse"));
        assert_eq!(name_of(26727), Some("Alnitak"));
        assert_eq!(name_of(1), None);
    }
}
